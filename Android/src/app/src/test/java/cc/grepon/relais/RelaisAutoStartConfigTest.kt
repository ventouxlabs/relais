package cc.grepon.relais

import android.content.Context
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.RuntimeEnvironment

@RunWith(RobolectricTestRunner::class)
class RelaisAutoStartConfigTest {

  private val context: Context get() = RuntimeEnvironment.getApplication()

  @Test fun `auto-start defaults off and persists changes`() {
    assertFalse(RelaisConfig.autoStartEnabled(context))

    RelaisConfig.setAutoStart(context, true)
    assertTrue(RelaisConfig.autoStartEnabled(context))

    RelaisConfig.setAutoStart(context, false)
    assertFalse(RelaisConfig.autoStartEnabled(context))
  }
}
